
using System;
using System.Data;
using System.Windows.Forms;
using THEPA_POS.Data.Repositories;
using THEPA_POS.Domain.Entities;

namespace THEPA_POS.Forms
{
    public partial class ProductEditorForm : Form
    {
        private readonly ProductRepository productRepository =
            new ProductRepository();

        private readonly CategoryRepository categoryRepository =
            new CategoryRepository();

        private readonly int loggedInUserId;
        private readonly int? editingProductId;

        private Product existingProduct;

        // ADD MODE
        public ProductEditorForm(int userId)
        {
            InitializeComponent();

            loggedInUserId = userId;
            editingProductId = null;

            InitializeEditor();
        }

        // UPDATE MODE
        public ProductEditorForm(int userId, int productId)
        {
            InitializeComponent();

            loggedInUserId = userId;
            editingProductId = productId;

            InitializeEditor();
        }

        private void InitializeEditor()
        {
            // SKU and barcode are generated by SQL Server.
            lblSku.Visible = false;
            txtSku.Visible = false;
            lblBarcode.Visible = false;
            txtBarcode.Visible = false;

            btnSave.Click += btnSave_Click;

            LoadCategories();

            if (editingProductId.HasValue && btnSave.Enabled)
            {
                LoadProductForEditing(editingProductId.Value);
            }
            else
            {
                this.Text = "Add Product";
                lblTitle.Text = "Add Product";
            }
        }

        private void LoadCategories()
        {
            try
            {
                DataTable categories = categoryRepository.GetAll();

                cmbCategory.DataSource = categories;
                cmbCategory.DisplayMember = "Name";
                cmbCategory.ValueMember = "CategoryId";
                cmbCategory.SelectedIndex = -1;
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Unable to load categories.\n\n" + ex.Message,
                    "THEPA POS",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);

                btnSave.Enabled = false;
            }
        }

        private void LoadProductForEditing(int productId)
        {
            try
            {
                DataTable products = productRepository.GetAll();
                DataRow[] rows = products.Select(
                    "ProductId = " + productId);

                if (rows.Length == 0)
                {
                    MessageBox.Show(
                        "The selected product could not be found.",
                        "THEPA POS",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    btnSave.Enabled = false;
                    return;
                }

                DataRow row = rows[0];

                existingProduct = new Product
                {
                    ProductId = productId,
                    Sku = Convert.ToString(row["Sku"]),
                    Barcode = Convert.ToString(row["Barcode"]),
                    Name = Convert.ToString(row["Name"]),
                    CategoryId = Convert.ToInt32(row["CategoryId"]),
                    Price = Convert.ToDecimal(row["Price"]),
                    Cost = Convert.ToDecimal(row["Cost"]),
                    StockQty = Convert.ToInt32(row["StockQty"]),
                    ReorderLevel = Convert.ToInt32(row["ReorderLevel"]),
                    IsActive = Convert.ToBoolean(row["IsActive"])
                };

                txtSku.Text = existingProduct.Sku;
                txtBarcode.Text = existingProduct.Barcode;
                txtName.Text = existingProduct.Name;

                cmbCategory.SelectedValue = existingProduct.CategoryId;

                numPrice.Value = existingProduct.Price;
                numCost.Value = existingProduct.Cost;
                numStock.Value = existingProduct.StockQty;
                numReorder.Value = existingProduct.ReorderLevel;

                chkActive.Checked = existingProduct.IsActive;

                this.Text = "Update Product";
                lblTitle.Text = "Update Product";
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Unable to load product details.\n\n" + ex.Message,
                    "THEPA POS",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);

                btnSave.Enabled = false;
            }
        }

        private void btnSave_Click(object sender, EventArgs e)
        {
            if (string.IsNullOrWhiteSpace(txtName.Text))
            {
                MessageBox.Show("Please enter the product name.");
                txtName.Focus();
                return;
            }

            if (cmbCategory.SelectedValue == null ||
                cmbCategory.SelectedValue is DataRowView)
            {
                MessageBox.Show("Please select a category.");
                cmbCategory.Focus();
                return;
            }

            if (numPrice.Value <= 0)
            {
                MessageBox.Show(
                    "Selling price must be greater than zero.");
                numPrice.Focus();
                return;
            }

            if (numCost.Value < 0 ||
                numStock.Value < 0 ||
                numReorder.Value < 0)
            {
                MessageBox.Show(
                    "Cost, stock, and reorder level cannot be negative.");
                return;
            }

            try
            {
                if (editingProductId.HasValue)
                {
                    // Preserve the original ID, SKU, barcode, and stock.
                    existingProduct.Name = txtName.Text.Trim();
                    existingProduct.CategoryId =
                        Convert.ToInt32(cmbCategory.SelectedValue);
                    existingProduct.Price = numPrice.Value;
                    existingProduct.Cost = numCost.Value;
                    existingProduct.StockQty = Convert.ToInt32(numStock.Value);
                    existingProduct.ReorderLevel =
                        Convert.ToInt32(numReorder.Value);

                    productRepository.Update(existingProduct);

                    MessageBox.Show(
                        "Product updated successfully!",
                        "THEPA POS",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Information);
                }
                else
                {
                    Product product = new Product
                    {
                        Name = txtName.Text.Trim(),
                        CategoryId =
                            Convert.ToInt32(cmbCategory.SelectedValue),
                        Price = numPrice.Value,
                        Cost = numCost.Value,
                        StockQty = Convert.ToInt32(numStock.Value),
                        ReorderLevel = Convert.ToInt32(numReorder.Value),
                        Image = null
                    };

                    int newProductId =
                        productRepository.Insert(product, loggedInUserId);

                    MessageBox.Show(
                        "Product added successfully!\nProduct ID: " +
                        newProductId,
                        "THEPA POS",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Information);
                }

                this.DialogResult = DialogResult.OK;
                this.Close();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Unable to save product.\n\n" + ex.Message,
                    "THEPA POS",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }
    }
}
